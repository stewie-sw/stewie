// Generate TypeScript types from the contract JSON Schemas (the single source of truth, D-R11).
// Output is committed; CI regenerates it and fails on any difference.
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const SCHEMAS = ["site", "body", "dem_bundle", "assessment", "assessment_request"];
const BANNER = "/* Generated by web/scripts/gen-contracts.mjs from crates/stewie-contracts/schema. Do not edit. */";

for (const name of SCHEMAS) {
  const schema = JSON.parse(await readFile(new URL(`../../crates/stewie-contracts/schema/${name}.schema.json`, import.meta.url), "utf8"));
  const ts = await compile(schema, schema.title, { bannerComment: BANNER, additionalProperties: false, style: { semi: true } });
  await writeFile(new URL(`../src/contracts/${name}.ts`, import.meta.url), ts);
}
